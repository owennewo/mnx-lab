// Mirrors the spec's MusicXML comparisons into converters/fixtures/w3c-comparisons/.
//
// The MNX half of each pair is already mirrored — sync-spec-examples.mjs owns
// scenarios/spec/, one directory per worked example. This script owns the
// MusicXML half, and it exists for the same reason: the pinned submodule is
// the source, but a test must not require it. `git worktree add` does not
// populate vendor/mnx and a fresh clone has it empty, so the oracle reads
// COMMITTED fixtures and this script is how they are refreshed when the pin
// moves.
//
// converters/fixtures/w3c-comparisons/ is owned by this script. Do not
// hand-edit it. The files are the W3C Community Group's, reproduced here as
// test fixtures with attribution in the directory's README.
//
// Usage: npm run sync:musicxml-comparisons
import fs from 'node:fs';
import path from 'node:path';
import { ROOT } from '../../harness/verify/check-scenarios.mjs';
import { loadMusicXmlComparisons, specRevision, pinIsUpstream } from './specSource.mjs';

const OUT_DIR = path.join(ROOT, 'converters', 'fixtures', 'w3c-comparisons');

const README = slugs => `# W3C MNX example comparisons — the MusicXML half

**Generated by \`npm run sync:musicxml-comparisons\`. Do not hand-edit.**

${slugs.length} MusicXML documents, each the W3C Music Notation Community Group's own
rendering of one MNX worked example into MusicXML 3.1. They come from
\`spectools.exampledocumentcomparison\` in the pinned \`vendor/mnx\` fixture — the data
behind the side-by-side on each example's reference page.

Every file pairs exactly with \`scenarios/spec/<slug>/\`, which holds the same music as
MNX along with its layout goldens and human verification record. That pairing is what
makes them an oracle rather than a corpus: the MNX is not our answer, it is the
spec's.

They are reproduced here as test fixtures so the oracle runs without the submodule.
Copyright remains with the W3C Music Notation Community Group; see
\`vendor/mnx\` for the upstream sources and their terms.

Consumed by \`harness/conformance/musicxml-oracle.test.ts\`
(roadmap item: \`core-musicxml-w3c-oracle.md\`).
`;

function main() {
  const comparisons = loadMusicXmlComparisons();
  const revision = specRevision();

  fs.mkdirSync(OUT_DIR, { recursive: true });

  // Remove files for slugs the pin no longer carries, so a moved pin cannot
  // leave an orphan fixture the oracle keeps testing against nothing.
  const expected = new Set(comparisons.map(c => `${c.slug}.musicxml`));
  expected.add('README.md');
  for (const existing of fs.readdirSync(OUT_DIR)) {
    if (!expected.has(existing)) {
      fs.rmSync(path.join(OUT_DIR, existing));
      console.log(`  removed ${existing} (no longer in the pin)`);
    }
  }

  let written = 0;
  let unchanged = 0;
  for (const { slug, xml } of comparisons) {
    const file = path.join(OUT_DIR, `${slug}.musicxml`);
    const previous = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (previous === xml) {
      unchanged++;
      continue;
    }
    fs.writeFileSync(file, xml);
    console.log(`  ${previous === null ? 'added' : 'updated'} ${slug}.musicxml`);
    written++;
  }

  fs.writeFileSync(path.join(OUT_DIR, 'README.md'), README(comparisons));

  console.log(
    `\nsync:musicxml-comparisons: ${comparisons.length} comparisons ` +
      `(${written} written, ${unchanged} unchanged) from spec ${revision}` +
      `${pinIsUpstream() ? '' : ' — WARNING: pin is not an upstream commit'}`
  );
}

main();
