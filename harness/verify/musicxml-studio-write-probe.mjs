import os from 'node:os';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawn, execFileSync } from 'node:child_process';
import { once } from 'node:events';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
import { devtoolsPort, connect, client, waitFor } from './browserHarness.mjs';
import { startLocalLibrary } from './localLibrary.mjs';
const root = fileURLToPath(new URL('../../', import.meta.url));
const library = await startLocalLibrary();
const { origin } = library;
const out = process.env.MUSICXML_WRITE_DIR ?? '/tmp/mnx-musicxml-studio-write'; await fs.mkdir(out, { recursive: true });
const auth = library.session;
const headers = { Authorization: `Bearer ${library.writeToken}`, 'Cf-Access-Jwt-Assertion': auth.machine };
const hash = b => createHash('sha256').update(b).digest('hex');
const fixture = '01a-Pitches-Pitches';
const bytes = await fs.readFile(path.join(root, `converters/fixtures/musicxml-suite/xmlFiles/${fixture}.musicxml`));
const gp = await fs.readFile(path.join(root, 'converters/fixtures/Triplets-and-graces.gp'));
const id = 'MusicXmlTitle-' + Date.now();
const manifest = { expected_revision: null, source: { kind: 'soundslice', id }, renditions: [
  { id: id+'-xml', format: 'musicxml', role: 'original', producer: 'local-assessment', producer_version: null, producer_options: null, filename: fixture+'.musicxml', sha256: hash(bytes), file: 'score' },
  { id: id+'-gp', format: 'gp', role: 'export', producer: 'local-assessment', producer_version: null, producer_options: null, filename: 'seed.gp', sha256: hash(gp), file: 'seed' }
], recordings: [], tags: [], canonical: { mode: 'initialize', rendition_id: id+'-gp' }, derived_tags: [{ dimension: 'title', value: fixture, source_ref: 'test' }] };
const form = new FormData(); form.set('manifest', JSON.stringify(manifest)); form.set('score', new Blob([bytes]), fixture+'.musicxml'); form.set('seed', new Blob([gp]), 'seed.gp');
const ingested = await fetch(origin+'/api/library/ingest', { method: 'POST', headers, body: form });
assert.equal(ingested.status, 200, await ingested.clone().text());
const initial = (await ingested.json()).snapshot; const pieceId = initial.piece.id;
const get = async url => { const r = await fetch(origin+'/api/library'+url, { headers: { 'Cf-Access-Jwt-Assertion': auth.browser } }); assert.equal(r.status, 200); return r; };
const snapshot = async () => (await (await get('/pieces/'+pieceId)).json()).snapshot;
const report = { fixture, sourceSha256: hash(bytes), applicationCommit: execFileSync('git', ['rev-parse','HEAD'], { cwd: root, encoding: 'utf8' }).trim(), captureScriptSha256: hash(await fs.readFile(fileURLToPath(import.meta.url))), shell: 'studio', pieceId };
const profile = await fs.mkdtemp(`${os.tmpdir()}/mnx-title-browser-`);
const chrome = spawn(process.env.CHROME_BIN ?? 'google-chrome', ['--headless=new','--no-sandbox','--disable-dev-shm-usage','--remote-debugging-port=0',`--user-data-dir=${profile}`,'about:blank'], { stdio: 'ignore' });
let ws;
try {
  ws = new WebSocket(await connect(await devtoolsPort(profile))); await once(ws, 'open'); const c = client(ws);
  await c.send('Runtime.enable'); await c.send('Page.enable'); await c.send('Network.enable');
  report.browser = (await c.send('Browser.getVersion')).result;
  await c.send('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false });
  await c.send('Emulation.setFocusEmulationEnabled', { enabled: true });
  await c.send('Network.setCookie', { name: 'CF_Authorization', value: auth.browser, url: origin, httpOnly: true, sameSite: 'Lax' });
  const page = "document.querySelector('mnx-studio')?.shadowRoot?.querySelector('mnx-studio-piece')";
  const piece = `${page}?.shadowRoot`; const viewer = `${piece}?.querySelector('mnx-document-viewer')`;
  const sheet = `${piece}?.querySelector('mnx-studio-save')?.shadowRoot`;
  const prompt = `${piece}?.querySelector('.version-title')`;
  const wait = (e, why) => waitFor(c, e, why, 30000);
  const read = () => c.evaluate(`${page}.editor.document`);
  const shot = async name => { const r = await c.send('Page.captureScreenshot'); await fs.writeFile(path.join(out,name+'.png'), Buffer.from(r.result.data,'base64')); };
  const saveDoc = async (name,d) => fs.writeFile(path.join(out,name+'.mnx.json'), JSON.stringify(d,null,2)+'\n');
  const key = async (code, key, vk, modifiers=0) => { await c.send('Input.dispatchKeyEvent',{type:'rawKeyDown',code,key,windowsVirtualKeyCode:vk,modifiers}); await c.send('Input.dispatchKeyEvent',{type:'keyUp',code,key,windowsVirtualKeyCode:vk,modifiers}); };
  await c.send('Page.navigate', { url: origin+'/studio/#/piece/'+pieceId });
  await wait(`!!${page}?.editor`, 'editable seed');
  await c.evaluate(`${piece}.querySelector('button.save').click()`);
  await wait(`!!${sheet}?.querySelector('[data-version="${id}-xml"] button')`, 'XML version');
  await c.evaluate(`${sheet}.querySelector('[data-version="${id}-xml"] button').click()`);
  await wait(`${page}.viewing?.id === '${id}-xml'`, 'view original XML');
  const imported = await c.evaluate(`${viewer}.mnxDoc.mnxJson`); assert.equal(imported._x?.mnxLab?.work?.title, undefined);
  await c.evaluate(`${sheet}.querySelector('[data-version="${id}-xml"] button').click()`);
  await wait(`!!${prompt}`, 'library title form');
  assert.equal(await c.evaluate(`${prompt}.querySelector('input').value`), fixture);
  await shot('title-prompt');
  await c.evaluate(`${prompt}.querySelector('button[type="button"]').click()`);
  assert.equal((await snapshot()).piece.canonical_rendition_id, id+'-gp');
  await c.evaluate(`${piece}.querySelector('.viewing button:last-child').click()`); await wait(`!!${prompt}`, 'reopen title form');
  await c.evaluate(`{ const i=${prompt}.querySelector('input'); i.value='   '; i.dispatchEvent(new Event('input')); }`);
  await wait(`${prompt}.querySelector('button[type="submit"]').disabled`, 'blank title refused');
  assert.equal((await snapshot()).piece.canonical_rendition_id, id+'-gp');
  const chosen = 'Imported pitch study';
  await c.evaluate(`{ const i=${prompt}.querySelector('input'); i.value=${JSON.stringify(chosen)}; i.dispatchEvent(new Event('input')); }`);
  await wait(`!${prompt}.querySelector('button[type="submit"]').disabled`, 'valid title');
  await c.evaluate(`${prompt}.requestSubmit()`);
  await wait(`!${page}.viewing && !!${page}.editor && ${page}.snapshot?.piece.canonical_rendition_id === '${id}-xml'`, 'editable XML current');
  assert.deepEqual(await read(), imported, 'promotion must not edit source metadata or notes');
  const current = await snapshot();
  assert.equal(current.tags.find(t=>t.dimension==='title').source_ref, 'library-title');
  assert.equal(current.tags.find(t=>t.dimension==='title').value, chosen);
  assert.equal(hash(Buffer.from(await (await get('/renditions/'+id+'-xml')).arrayBuffer())), hash(bytes));
  report.title = { cancelUnchanged: true, blankRefused: true, chosen, sourceUnchanged: true, documentUnchanged: true };
  await shot('editable-original'); await saveDoc('imported', imported);
  await c.evaluate(`${viewer}.focus()`); await key('ArrowUp','ArrowUp',38,1);
  await wait(`JSON.stringify(${page}.editor.document)!==${JSON.stringify(JSON.stringify(imported))}`, 'note transposition');
  const changed = await read();
  const notes = d => d.parts.flatMap(p=>p.measures.flatMap(m=>m.sequences.flatMap(s=>s.content.flatMap(e=>e.notes??[]))));
  const pitch = n => ({C:0,D:2,E:4,F:5,G:7,A:9,B:11}[n.pitch.step]+12*(n.pitch.octave+1)+(n.pitch.alter??0));
  const delta = notes(changed).map((n,i)=>pitch(n)-pitch(notes(imported)[i]));
  assert.equal(delta.filter(d=>d===1).length,1); assert.equal(delta.filter(d=>d!==0).length,1);
  const normalized = structuredClone(changed); notes(normalized).forEach((n,i)=>n.pitch=notes(imported)[i].pitch); assert.deepEqual(normalized,imported);
  await key('KeyZ','z',90,2); await wait(`JSON.stringify(${page}.editor.document)===${JSON.stringify(JSON.stringify(imported))}`, 'exact undo');
  await key('KeyY','y',89,2); await wait(`JSON.stringify(${page}.editor.document)===${JSON.stringify(JSON.stringify(changed))}`, 'exact redo');
  await saveDoc('edited', changed);
  await c.evaluate(`${piece}.querySelector('button.save').click()`);
  await wait(`!!${sheet}`, 'save sheet');
  await c.evaluate(`[...${sheet}.querySelectorAll('button')].find(b=>b.textContent.trim()==='Save now').click()`);
  await wait(`${page}.snapshot?.piece.canonical_rendition_id !== '${id}-xml' && ${piece}.querySelector('button.save').dataset.save === 'clean'`, 'GP checkpoint');
  const saved = await snapshot(); const rendition = saved.renditions.find(r=>r.id===saved.piece.canonical_rendition_id);
  assert.equal(rendition.format,'gp'); report.storage = JSON.parse(rendition.provenance);
  report.losses = await c.evaluate(`${page}.losses`); await shot('saved-loss-report');
  await c.send('Page.reload'); await wait(`!!${page}?.editor && !${page}.loading`, 'stored GP reopen');
  const reopened = await read(); await saveDoc('reopened',reopened);
  assert.equal(delta[0], 1, 'the selected edit is the first source note');
  assert.equal(pitch(notes(reopened)[0]), pitch(notes(changed)[0]), 'edited note must survive storage');
  const expectedPitches = notes(changed).map(pitch), actualPitches = notes(reopened).map(pitch);
  const remaining = [...actualPitches], missing = [];
  for (const value of expectedPitches) { if (remaining[0] === value) remaining.shift(); else missing.push(value); }
  assert.deepEqual(remaining, [], 'surviving pitches must keep source order and values');
  assert.equal(missing.length, 15, 'retain the measured pitch-range storage loss');
  assert.equal(report.storage.check.verdict, 'differs');
  assert.ok(report.storage.check.differences.some(d => d.kind === 'lost' && d.path.endsWith('/notes') && d.count === missing.length));
  assert.ok(report.storage.check.warnings.some(w => w.includes('outside the instrument')));
  assert.ok(report.losses.some(l => l.kind === 'lost' && l.path.endsWith('/notes')), 'the UI must expose the note loss');
  report.pitchStorage = { before: expectedPitches.length, after: actualPitches.length, missingMidiPitches: missing, verdict: 'lossy; 15 source notes lost, edited first note retained' };
  assert.equal((await snapshot()).tags.find(t=>t.dimension==='title').value, chosen);
  assert.equal(reopened._x?.mnxLab?.work?.title, undefined, 'library title must not become score metadata');
  assert.equal(hash(Buffer.from(await (await get('/renditions/'+id+'-xml')).arrayBuffer())),hash(bytes));
  report.edit = { changedNotes: 1, semitones: 1, undoRedo: 'exact', unrelatedData: 'unchanged before storage', reopenedEditedPitch: 'exact; other source notes have the separately reported GP losses', reopenedLibraryTitle: chosen };
  await c.evaluate(`${piece}.querySelector('button[slot="title-action"]').click()`);
  const details = `${piece}.querySelector('mnx-studio-edit-piece')?.shadowRoot`;
  await wait(`!!${details}?.querySelector('input')`, 'score metadata editor');
  assert.ok((await c.evaluate(`${details}.textContent`)).includes('library title was supplied'));
  await shot('metadata-editor'); report.metadataEditorReachable = true;
  report.consoleErrors=c.logs; assert.deepEqual(c.logs,[]); report.result='passed';
} catch(error) { report.error=error.stack; process.exitCode=1; }
finally { await fs.writeFile(path.join(out,'report.json'),JSON.stringify(report,null,2)+'\n'); ws?.close(); chrome.kill(); await once(chrome,'exit'); await fs.rm(profile,{recursive:true,force:true,maxRetries:5,retryDelay:100}); await library.close(); }
console.log(JSON.stringify(report,null,2));
